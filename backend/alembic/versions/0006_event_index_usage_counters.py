def _backfill() -> None:
    conn = op.get_bind()
    if conn.dialect.name == "postgresql":  # existing tables are under forced RLS: read across tenants
        conn.execute(sa.text("SELECT set_config('app.rls_bypass', 'on', true)"))
    records = sa.table("usage_records", sa.column("organization_id", sa.Uuid()), sa.column("period", sa.String()),
                       sa.column("metric", sa.String()), sa.column("quantity", sa.Numeric(20, 6)))
    counters = sa.table("usage_counters", sa.column("id", sa.Uuid()), sa.column("organization_id", sa.Uuid()), sa.column("period", sa.String()),
                        sa.column("metric", sa.String()), sa.column("quantity", sa.Numeric(20, 6)), sa.column("updated_at", app.db.UTCDateTime()))
    totals = conn.execute(sa.select(records.c.organization_id, records.c.period, records.c.metric, sa.func.sum(records.c.quantity))
                          .group_by(records.c.organization_id, records.c.period, records.c.metric)).all()
    now = app.db.utcnow()
    if totals:
        op.bulk_insert(counters, [{"id": uuid.uuid4(), "organization_id": o, "period": p, "metric": m, "quantity": q or 0, "updated_at": now}
                                  for o, p, m, q in totals])

    workflows = sa.table("workflows", sa.column("id", sa.Uuid()), sa.column("organization_id", sa.Uuid()),
                         sa.column("current_version_id", sa.Uuid()), sa.column("deleted_at", app.db.UTCDateTime()))
    versions = sa.table("workflow_versions", sa.column("id", sa.Uuid()), sa.column("definition", sa.JSON()))
    subs = sa.table("app_event_subscriptions", sa.column("id", sa.Uuid()), sa.column("organization_id", sa.Uuid()), sa.column("workflow_id", sa.Uuid()),
                    sa.column("node_key", sa.String()), sa.column("pattern", sa.String()), sa.column("exact_type", sa.String()))
    rows = []
    for wf_id, org_id, definition in conn.execute(sa.select(workflows.c.id, workflows.c.organization_id, versions.c.definition)
                                                  .join(versions, versions.c.id == workflows.c.current_version_id)
                                                  .where(workflows.c.deleted_at.is_(None))):
        for node in (definition or {}).get("nodes", []):
            pattern = str((node.get("config") or {}).get("event_type") or "").strip()[:120]
            if node.get("type") == "trigger.app_event" and pattern:
                rows.append({"id": uuid.uuid4(), "organization_id": org_id, "workflow_id": wf_id, "node_key": node["id"],
                             "pattern": pattern, "exact_type": None if pattern.endswith("*") else pattern})
    if rows:
        op.bulk_insert(subs, rows)


